create table if not exists public.freestyle_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.freestyle_images (
  id bigint generated by default as identity primary key,
  image_type text not null,
  target_key text not null,
  color_key text,
  upload_mode text not null default 'add',
  storage_path text not null unique,
  original_filename text,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.freestyle_products (
  id text primary key,
  name text not null,
  category text not null,
  price numeric(12,2),
  description text,
  colors text[] not null default '{}',
  sizes text[] not null default '{}',
  status text not null default 'Disponível',
  is_active boolean not null default true,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create or replace function public.is_freestyle_admin()
returns boolean language sql stable security definer
set search_path = public
as $$ select exists (select 1 from public.freestyle_admins where user_id = auth.uid()); $$;

revoke all on function public.is_freestyle_admin() from public;
grant execute on function public.is_freestyle_admin() to authenticated;

